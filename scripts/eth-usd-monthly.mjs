// Builds src/landing/eth-usd-monthly.ts: ETH's average dollar price per
// UTC month, the mean of the month's daily closes on Coinbase's public
// ETH-USD market (api.exchange.coinbase.com, no key, no account). The
// landing page values each ETH deposit and bounty at its month's price
// (src/landing/money.ts). Run from the repo root, after a month closes:
//
//   node scripts/eth-usd-monthly.mjs 2020-01 2026-10
//
// The two arguments are the first and last month to write, inclusive.
import { writeFileSync } from 'node:fs'

const [from = '2020-01', to] = process.argv.slice(2)
if (!to) throw new Error('usage: node scripts/eth-usd-monthly.mjs <from YYYY-MM> <to YYYY-MM>')
const start = Date.parse(`${from}-01T00:00:00Z`)
const [ty, tm] = to.split('-').map(Number)
const end = Date.UTC(ty, tm, 1) // first day after the last month
const DAY = 86_400_000
const closes = new Map()
for (let at = start; at < end; at += 300 * DAY) {
  const stop = Math.min(at + 299 * DAY, end - DAY)
  const url = `https://api.exchange.coinbase.com/products/ETH-USD/candles?granularity=86400&start=${new Date(at).toISOString()}&end=${new Date(stop).toISOString()}`
  const response = await fetch(url, { headers: { 'user-agent': 'curate-landing-build' } })
  if (!response.ok) throw new Error(`${response.status} for ${url}`)
  // [time, low, high, open, close, volume], newest first
  for (const [time, , , , close] of await response.json())
    if (time * 1000 >= start && time * 1000 < end) closes.set(time, close)
  await new Promise((resolve) => setTimeout(resolve, 400))
}
const months = new Map()
for (const [time, close] of [...closes].sort((a, b) => a[0] - b[0])) {
  const key = new Date(time * 1000).toISOString().slice(0, 7)
  const month = months.get(key) ?? []
  month.push(close)
  months.set(key, month)
}
const rows = [...months].map(([key, list]) => {
  const mean = list.reduce((sum, v) => sum + v, 0) / list.length
  return `  '${key}': ${mean.toFixed(2)}, // ${list.length} days`
})
const body = `/*
 * ETH's average dollar price per UTC month: the mean of the month's daily
 * closes on Coinbase's public ETH-USD market. Generated by
 * scripts/eth-usd-monthly.mjs (${from} to ${to}); do not edit by hand. A month
 * after the last one here is valued at today's price (src/landing/money.ts).
 */
export const ETH_USD_MONTHLY: Record<string, number> = {
${rows.join('\n')}
}
`
writeFileSync('src/landing/eth-usd-monthly.ts', body)
console.log(`${months.size} months, ${closes.size} days`)
